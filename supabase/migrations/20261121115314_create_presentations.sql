-- Presentaciones de cada variedad.
-- El aroma es opcional; la combinación variedad + aroma + peso + unidad no se repite.
-- El índice único compuesto cubre la clave foránea variety_id.

create table public.presentations (
  id bigint generated by default as identity primary key,
  variety_id bigint not null references public.varieties (id) on delete cascade,
  aroma_id bigint references public.aromas (id) on delete restrict,
  description text,
  weight numeric(8, 2) not null,
  unit text not null,
  price numeric(10, 2) not null,
  stock integer not null default 0,
  tag text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz,
  constraint presentations_weight_positive check (weight > 0),
  constraint presentations_price_not_negative check (price >= 0),
  constraint presentations_stock_not_negative check (stock >= 0),
  constraint presentations_unit_length check (btrim(unit) <> '' and length(btrim(unit)) <= 20),
  constraint presentations_tag_length check (tag is null or length(btrim(tag)) between 1 and 50)
);

create unique index presentations_variety_aroma_weight_unit_unique
  on public.presentations (variety_id, aroma_id, weight, unit) nulls not distinct;

create index presentations_aroma_id_idx on public.presentations (aroma_id);
