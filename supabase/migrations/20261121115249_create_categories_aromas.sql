-- Categorías y aromas del catálogo.
-- Los nombres son únicos sin distinguir mayúsculas, minúsculas ni espacios extremos.
-- Sin timestamps: la spec no los pide para estas dos tablas.

create table public.categories (
  id bigint generated by default as identity primary key,
  name text not null,
  constraint categories_name_not_blank check (btrim(name) <> '')
);

create unique index categories_name_unique on public.categories (lower(btrim(name)));

create table public.aromas (
  id bigint generated by default as identity primary key,
  name text not null,
  constraint aromas_name_not_blank check (btrim(name) <> '')
);

create unique index aromas_name_unique on public.aromas (lower(btrim(name)));
