-- Variedades de cada producto.
-- El nombre es único dentro del producto, ignorando mayúsculas y espacios extremos.
-- El índice único compuesto cubre la clave foránea product_id.

create table public.varieties (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products (id) on delete cascade,
  name text not null,
  description text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz,
  constraint varieties_name_not_blank check (btrim(name) <> '')
);

create unique index varieties_product_name_unique
  on public.varieties (product_id, lower(btrim(name)));
