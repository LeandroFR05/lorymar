-- Imágenes de cada presentación.
-- Se guarda la ruta del archivo, no la URL completa. Puede haber varias principales.

create table public.pictures (
  id bigint generated by default as identity primary key,
  presentation_id bigint not null references public.presentations (id) on delete cascade,
  storage_path text not null,
  is_main boolean not null default false,
  constraint pictures_storage_path_not_blank check (btrim(storage_path) <> '')
);

create index pictures_presentation_id_idx on public.pictures (presentation_id);
